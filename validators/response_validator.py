def validate_status_code(response, expected_status):
    # "response" = the actual API response we received.
    # "expected_status" = the status code we expect.

    assert response.status_code == expected_status
    # Check whether the actual status code matches the expected status code.

def validate_response_not_empty(response):
    # "response" = the actual API response we received.

    assert response.json() != {}
    # Check that the API returned some JSON data
    # instead of an empty JSON object.

def validate_ai_answer_not_empty(answer):
    # "answer" = the actual text generated by the AI.

    assert answer != ""
    # Check that the AI returned some text.